#[derive(Debug, Clone)]
pub struct Issue {
    pub id: String,
    pub title: String,
    pub body: String,
    pub status: Status,
    pub visibility: Visibility,
    pub issuer_id: String,
    pub issuer_name: String,
    /// False once the issuer's account is deactivated.
    pub issuer_active: bool,
    pub assignee_id: Option<String>,
    pub assignee_name: Option<String>,
    pub assignee_active: bool,
    /// Unix milliseconds.
    pub start_at: Option<i64>,
    /// Unix milliseconds.
    pub due_at: Option<i64>,
    pub created_at: i64,
    pub updated_at: i64,
    pub labels: Vec<Label>,
    /// Set on occurrences generated by a recurring series.
    pub series_id: Option<String>,
}

impl Issue {
    pub(crate) fn from_row(row: &Row) -> Self {
        Issue {
            id: row.text("id"),
            title: row.text("title"),
            body: row.text("body"),
            status: Status::parse(&row.text("status")).unwrap_or(Status::Open),
            visibility: Visibility::parse(&row.text("visibility")).unwrap_or(Visibility::Private),
            issuer_id: row.text("issuer_id"),
            issuer_name: row.text("issuer_name"),
            issuer_active: row.flag("issuer_active"),
            assignee_id: row.opt_text("assignee_id"),
            assignee_name: row.opt_text("assignee_name"),
            assignee_active: row.flag("assignee_active"),
            start_at: row.opt_int("start_at"),
            due_at: row.opt_int("due_at"),
            created_at: row.int("created_at"),
            updated_at: row.int("updated_at"),
            labels: Vec::new(),
            series_id: row.opt_text("series_id"),
        }
    }

    pub fn is_overdue(&self, now: i64) -> bool {
        self.status != Status::Done && self.due_at.is_some_and(|due| due < now)
    }
}

/// A recurring event; each occurrence becomes its own issue.
#[derive(Debug, Clone)]
pub struct Series {
    pub id: String,
    pub title: String,
    pub body: String,
    pub visibility: Visibility,
    pub issuer_id: String,
    pub issuer_name: String,
    pub issuer_active: bool,
    pub assignee_id: Option<String>,
    pub assignee_name: Option<String>,
    pub assignee_active: bool,
    pub rule: Recurrence,
    /// Zone the rule's local dates and times are in.
    pub timezone: chrono_tz::Tz,
    /// Occurrences starting at or before this time are never generated.
    pub effective_from: i64,
    pub generated_until: Option<chrono::NaiveDate>,
    pub stopped_at: Option<i64>,
    pub created_at: i64,
    pub updated_at: i64,
    pub labels: Vec<Label>,
}

impl Series {
    pub(crate) fn from_row(row: &Row) -> Self {
        let start_date = parse_date(&row.text("start_date")).unwrap_or_default();
        Series {
            id: row.text("id"),
            title: row.text("title"),
            body: row.text("body"),
            visibility: Visibility::parse(&row.text("visibility")).unwrap_or(Visibility::Private),
            issuer_id: row.text("issuer_id"),
            issuer_name: row.text("issuer_name"),
            issuer_active: row.flag("issuer_active"),
            assignee_id: row.opt_text("assignee_id"),
            assignee_name: row.opt_text("assignee_name"),
            assignee_active: row.flag("assignee_active"),
            rule: Recurrence {
                freq: Freq::parse(&row.text("freq")).unwrap_or(Freq::Weekly),
                weekdays: u8::try_from(row.int("weekdays") & 0x7f).unwrap_or(0),
                start_date,
                until: row.opt_text("until_date").and_then(|d| parse_date(&d)),
                start_minute: u32::try_from(row.int("start_minute").clamp(0, 1439)).unwrap_or(0),
                duration_min: row.int("duration_min").max(0),
            },
            timezone: row
                .text("timezone")
                .parse()
                .unwrap_or(chrono_tz::Asia::Taipei),
            effective_from: row.int("effective_from"),
            generated_until: row.opt_text("generated_until").and_then(|d| parse_date(&d)),
            stopped_at: row.opt_int("stopped_at"),
            created_at: row.int("created_at"),
            updated_at: row.int("updated_at"),
            labels: Vec::new(),
        }
    }
}

/// When a user's personal reminder for an issue fires.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reminder {
    /// Unix milliseconds.
    Exact(i64),
    /// Minutes before the issue's due time.
    BeforeDue(i64),
    /// Minutes before the issue's start time.
    BeforeStart(i64),
}

impl Reminder {
    /// 1 day, 6..=1 hours, 59..=1 minutes before the start or due time.
    pub fn allowed_offsets() -> Vec<(i64, String)> {
        let mut offsets = vec![(24 * 60, "1 天前".to_owned())];
        offsets.extend((1..=6).rev().map(|h| (h * 60, format!("{h} 小時前"))));
        offsets.extend((1..=59).rev().map(|m| (m, format!("{m} 分鐘前"))));
        offsets
    }

    pub fn is_allowed_offset(minutes: i64) -> bool {
        Self::allowed_offsets().iter().any(|(m, _)| *m == minutes)
    }

    /// Absolute fire time, or `None` when it depends on a missing start or due time.
    pub fn fire_at(self, start_at: Option<i64>, due_at: Option<i64>) -> Option<i64> {
        match self {
            Reminder::Exact(at) => Some(at),
            Reminder::BeforeDue(minutes) => due_at.map(|due| due - minutes * 60_000),
            Reminder::BeforeStart(minutes) => start_at.map(|start| start - minutes * 60_000),
        }
    }

    /// Stored `mode` value and the offset in minutes for relative reminders.
    pub fn mode(self) -> (&'static str, Option<i64>) {
        match self {
            Reminder::Exact(_) => ("exact", None),
            Reminder::BeforeDue(minutes) => ("before_due", Some(minutes)),
            Reminder::BeforeStart(minutes) => ("before_start", Some(minutes)),
        }
    }

    pub fn from_row(row: &Row) -> Option<Self> {
        match row.text("mode").as_str() {
            "exact" => Some(Reminder::Exact(row.int("remind_at"))),
            "before_due" => Some(Reminder::BeforeDue(row.int("offset_min"))),
            "before_start" => Some(Reminder::BeforeStart(row.int("offset_min"))),
            _ => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reminder_offsets_cover_spec() {
        let offsets: Vec<i64> = Reminder::allowed_offsets()
            .iter()
            .map(|(m, _)| *m)
            .collect();
        assert_eq!(offsets.len(), 1 + 6 + 59);
        assert!(Reminder::is_allowed_offset(1440));
        assert!(Reminder::is_allowed_offset(360));
        assert!(Reminder::is_allowed_offset(60));
        assert!(Reminder::is_allowed_offset(59));
        assert!(Reminder::is_allowed_offset(1));
        assert!(!Reminder::is_allowed_offset(90));
        assert!(!Reminder::is_allowed_offset(0));
    }

    #[test]
    fn relative_reminders_need_their_anchor_time() {
        assert_eq!(Reminder::BeforeDue(60).fire_at(Some(1), None), None);
        assert_eq!(Reminder::BeforeStart(60).fire_at(None, Some(1)), None);
        assert_eq!(
            Reminder::BeforeStart(1).fire_at(Some(10_000_000), None),
            Some(10_000_000 - 60_000)
        );
        assert_eq!(
            Reminder::BeforeDue(60).fire_at(None, Some(10_000_000)),
            Some(10_000_000 - 3_600_000)
        );
        assert_eq!(Reminder::Exact(5).fire_at(None, None), Some(5));
    }

    #[test]
    fn status_round_trips() {
        for s in Status::ALL {
            assert_eq!(Status::parse(s.as_str()), Some(s));
        }
        assert_eq!(Status::parse("closed"), None);
    }
}
