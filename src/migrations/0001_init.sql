-- Shared by MariaDB (sqlx) and D1 (wrangler): keep to the SQL subset both support.
-- Primary keys repeat NOT NULL because SQLite allows NULL in non-INTEGER primary keys.
CREATE TABLE users (
    id                   CHAR(26)     NOT NULL PRIMARY KEY,
    username             VARCHAR(32)  NOT NULL UNIQUE,
    display_name         VARCHAR(32)  NOT NULL,
    password_hash        VARCHAR(255) NOT NULL,
    is_admin             BIGINT       NOT NULL DEFAULT 0,
    is_active            BIGINT       NOT NULL DEFAULT 1,
    must_change_password BIGINT       NOT NULL DEFAULT 0,
    created_at           BIGINT       NOT NULL
);

CREATE TABLE sessions (
    token      CHAR(64) NOT NULL PRIMARY KEY,
    user_id    CHAR(26) NOT NULL,
    expires_at BIGINT   NOT NULL,
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_sessions_user ON sessions (user_id);
CREATE INDEX idx_sessions_expires ON sessions (expires_at);

CREATE TABLE settings (
    name  VARCHAR(64)  NOT NULL PRIMARY KEY,
    value VARCHAR(255) NOT NULL
);

CREATE TABLE labels (
    id         CHAR(26)    NOT NULL PRIMARY KEY,
    name       VARCHAR(32) NOT NULL UNIQUE,
    color      CHAR(7)     NOT NULL,
    is_system  BIGINT      NOT NULL DEFAULT 0,
    created_by CHAR(26)    NULL,
    created_at BIGINT      NOT NULL,
    FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE issues (
    id          CHAR(26)     NOT NULL PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    body        TEXT         NOT NULL,
    status      VARCHAR(16)  NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'in_progress', 'done')),
    visibility  VARCHAR(16)  NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
    issuer_id   CHAR(26)     NOT NULL,
    assignee_id CHAR(26)     NULL,
    start_at    BIGINT       NULL,
    due_at      BIGINT       NULL,
    created_at  BIGINT       NOT NULL,
    updated_at  BIGINT       NOT NULL,
    FOREIGN KEY (issuer_id) REFERENCES users (id),
    FOREIGN KEY (assignee_id) REFERENCES users (id)
);

CREATE INDEX idx_issues_issuer ON issues (issuer_id, updated_at);
CREATE INDEX idx_issues_assignee ON issues (assignee_id, due_at);
CREATE INDEX idx_issues_visibility ON issues (visibility, updated_at);

CREATE TABLE issue_labels (
    issue_id CHAR(26) NOT NULL,
    label_id CHAR(26) NOT NULL,
    PRIMARY KEY (issue_id, label_id),
    FOREIGN KEY (issue_id) REFERENCES issues (id) ON DELETE CASCADE,
    FOREIGN KEY (label_id) REFERENCES labels (id) ON DELETE CASCADE
);

CREATE INDEX idx_issue_labels_label ON issue_labels (label_id);

CREATE TABLE reminders (
    issue_id    CHAR(26)    NOT NULL,
    user_id     CHAR(26)    NOT NULL,
    mode        VARCHAR(16) NOT NULL CHECK (mode IN ('exact', 'before_due')),
    offset_min  BIGINT      NULL,
    remind_at   BIGINT      NOT NULL,
    notified_at BIGINT      NULL,
    PRIMARY KEY (issue_id, user_id),
    FOREIGN KEY (issue_id) REFERENCES issues (id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_reminders_due ON reminders (user_id, notified_at, remind_at);

