/// One `<option>` / radio / checkbox choice.
pub struct Opt {
    pub value: String,
    pub label: String,
    pub selected: bool,
}

impl Opt {
    pub fn new(value: impl Into<String>, label: impl Into<String>, current: &str) -> Self {
        let value = value.into();
        let selected = value == current;
        Opt {
            value,
            label: label.into(),
            selected,
        }
    }
}

pub struct LabelView {
    pub name: String,
    pub color: String,
}

impl From<&Label> for LabelView {
    fn from(l: &Label) -> Self {
        LabelView {
            name: l.name.clone(),
            color: l.color.clone(),
        }
    }
}

pub struct IssueRow {
    pub id: String,
    pub title: String,
    pub status: &'static str,
    pub status_label: &'static str,
    pub is_public: bool,
    pub assignee: String,
    pub issuer: String,
    pub labels: Vec<LabelView>,
    pub due: String,
    /// Unix milliseconds, 0 when unset; the page script updates `due_label` from it.
    pub due_ms: i64,
    pub due_label: String,
    /// `overdue`, `soon` or empty.
    pub due_class: &'static str,
    pub updated: String,
    /// The viewer may change the status (board buttons).
    pub can_move: bool,
    /// The viewer may take it over (list shortcut).
    pub can_claim: bool,
    /// Generated by a recurring series.
    pub in_series: bool,
    /// Start time, shown for occurrences of a series.
    pub start: String,
}

impl IssueRow {
    pub fn new(issue: &Issue, viewer: &User, tz: Tz, now: i64) -> Self {
        let (due, due_label, due_class) = match issue.due_at {
            Some(due) => {
                let class = if issue.is_overdue(now) {
                    "overdue"
                } else if issue.status != Status::Done && due - now < 24 * 3_600_000 {
                    "soon"
                } else {
                    ""
                };
                let label = if issue.status == Status::Done {
                    format!("到期 {}", time::display(due, tz))
                } else {
                    time::due_label(due, now)
                };
                (time::display(due, tz), label, class)
            }
            None => (String::new(), String::new(), ""),
        };
        IssueRow {
            id: issue.id.clone(),
            title: issue.title.clone(),
            status: issue.status.as_str(),
            status_label: issue.status.label(),
            is_public: issue.visibility == crate::domain::Visibility::Public,
            assignee: issue.assignee_name.clone().unwrap_or_default(),
            issuer: issue.issuer_name.clone(),
            labels: issue.labels.iter().map(LabelView::from).collect(),
            due,
            due_ms: issue.due_at.unwrap_or(0),
            due_label,
            due_class,
            updated: time::display(issue.updated_at, tz),
            can_move: permission::can_change_status(issue, viewer),
            can_claim: permission::can_claim(issue, &viewer.id),
            in_series: issue.series_id.is_some(),
            start: issue
                .start_at
                .map(|t| time::display(t, tz))
                .unwrap_or_default(),
        }
    }
}

