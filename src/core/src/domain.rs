#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    Open,
    InProgress,
    Done,
}

impl Status {
    pub const ALL: [Status; 3] = [Status::Open, Status::InProgress, Status::Done];

    pub fn as_str(self) -> &'static str {
        match self {
            Status::Open => "open",
            Status::InProgress => "in_progress",
            Status::Done => "done",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Status::Open => "待處理",
            Status::InProgress => "進行中",
            Status::Done => "已完成",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|v| v.as_str() == s)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Visibility {
    Private,
    Public,
}

impl Visibility {
    pub fn as_str(self) -> &'static str {
        match self {
            Visibility::Private => "private",
            Visibility::Public => "public",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Visibility::Private => "私人",
            Visibility::Public => "公開",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        match s {
            "private" => Some(Visibility::Private),
            "public" => Some(Visibility::Public),
            _ => None,
        }
    }
}

#[derive(Debug, Clone)]
pub struct User {
    pub id: String,
    pub username: String,
    pub display_name: String,
    pub email: Option<String>,
    pub is_admin: bool,
    pub is_active: bool,
    pub must_change_password: bool,
}

impl User {
    pub(crate) fn from_row(row: &Row) -> Self {
        User {
            id: row.text("id"),
            username: row.text("username"),
            display_name: row.text("display_name"),
            email: row.opt_text("email").filter(|e| !e.is_empty()),
            is_admin: row.flag("is_admin"),
            is_active: row.flag("is_active"),
            must_change_password: row.flag("must_change_password"),
        }
    }
}

